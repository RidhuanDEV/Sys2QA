import { readdirSync, readFileSync, statSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { describe, expect, it } from "vitest";
import { scanFiles } from "../security/harness/index.js";
import { computeMetrics, loadGroundTruth, stubProducer } from "./harness/index.js";

const ROOT = fileURLToPath(new URL("../../fixtures/benchmarks/", import.meta.url));
const FIXTURES = readdirSync(ROOT).filter((f) => statSync(join(ROOT, f)).isDirectory());
const common = JSON.parse(
  readFileSync(fileURLToPath(new URL("../../schemas/common.schema.json", import.meta.url)), "utf8"),
) as { $defs: Record<string, { enum: string[] }> };
const scenarioSchema = JSON.parse(
  readFileSync(fileURLToPath(new URL("../../schemas/scenario.schema.json", import.meta.url)), "utf8"),
) as {
  properties: {
    test_techniques: { items: { properties: { id: { enum: string[] } } } };
    qa_objective: { $ref?: string };
  };
};
const STOP_REASONS = new Set(common.$defs.stop_reason_code!.enum);
const CATEGORIES = new Set(common.$defs.workflow_category!.enum);
const TECHNIQUES = new Set(scenarioSchema.properties.test_techniques.items.properties.id.enum);
const GAP_TYPES = new Set([
  "contradiction",
  "external_boundary",
  "missing_evidence",
  "unsupported",
  "unobservable",
  "ambiguity",
]);

function filesUnder(dir: string): string[] {
  return readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((d) => d.isFile())
    .map((d) => join(d.parentPath, d.name));
}

describe("benchmark ground truth is consistent (IMP-013)", () => {
  it("has the four fixtures of Test Strategy §4", () => {
    expect(FIXTURES).toEqual(["F1-repository-only", "F2-url-only", "F3-combined", "F4-incomplete-evidence"]);
  });

  it.each(FIXTURES)("%s: every referenced entity is declared, and codes come from the contract", (fixture) => {
    const truth = loadGroundTruth(join(ROOT, fixture, "ground-truth"), fixture);
    const ids = new Set(truth.entities.map((e) => e.id));
    expect(ids.size).toBe(truth.entities.length);
    for (const e of truth.entities) expect(e.id.startsWith(`${e.kind}:`), e.id).toBe(true);
    const referenced = [
      ...truth.workflows.flatMap((w) => [
        w.entry_point,
        ...w.steps,
        ...w.branches.map((b) => b.from),
        ...w.external_boundaries,
        ...w.stop_points.flatMap((s) => (s.after ? [s.after] : [])),
      ]),
      ...truth.gaps.flatMap((g) => g.related),
    ];
    expect(referenced.filter((id) => !ids.has(id))).toEqual([]);
    for (const w of truth.workflows) {
      expect(CATEGORIES.has(w.category), `${w.key} category`).toBe(true);
      for (const s of w.stop_points) expect(STOP_REASONS.has(s.reason_code), `${w.key} ${s.reason_code}`).toBe(true);
    }
    for (const g of truth.gaps) expect(GAP_TYPES.has(g.type), g.key).toBe(true);
    for (const s of truth.scenarios.expected) expect(TECHNIQUES.has(s.technique), s.key).toBe(true);
    for (const f of truth.forbidden_claims)
      if (f.claim_text) expect(() => new RegExp(f.claim_text!, "i")).not.toThrow();
    expect(new Set(truth.workflows.map((w) => w.key)).size).toBe(truth.workflows.length);
  });

  it.each(FIXTURES)("%s: a producer that echoes the ground truth passes every gate", (fixture) => {
    const truth = loadGroundTruth(join(ROOT, fixture, "ground-truth"), fixture);
    const m = computeMetrics(truth, stubProducer(truth));
    expect(m.discovery.recall).toBe(1);
    expect(m.gates.filter((g) => !g.passed)).toEqual([]);
  });
});

describe("F1 ground truth matches its repository", () => {
  const repo = join(ROOT, "F1-repository-only", "repo");
  const source = filesUnder(repo)
    .map((f) => readFileSync(f, "utf8"))
    .join("\n");
  const truth = loadGroundTruth(join(ROOT, "F1-repository-only", "ground-truth"), "F1");
  const toExpress = (path: string) => path.replace(/\{(\w+)\}/g, ":$1");

  it("has at least six workflows, and every API route, page route and form exists in the code", () => {
    expect(truth.workflows.length).toBeGreaterThanOrEqual(6);
    for (const e of truth.entities) {
      const [kind, ...rest] = e.id.split(":");
      if (kind === "api")
        expect(source, e.id).toContain(`.${rest[0]!.toLowerCase()}("${toExpress(rest.slice(1).join(":"))}"`);
      if (kind === "page") expect(source, e.id).toContain(`path: "${toExpress(rest.slice(1).join(":"))}"`);
      if (kind === "form") expect(source, e.id).toContain(`id="${e.id.split("#")[1]}"`);
    }
  });

  it("contains the planted traps: secret, injection comment, generated code, install script, dynamic routes and dead code", () => {
    expect(scanFiles([repo]).map((l) => l.secret)).toEqual(["aws_access_key_id"]);
    expect(source).toContain("NOTE TO AI ASSISTANTS");
    expect(source).toContain("Code generated by Prisma. DO NOT EDIT.");
    expect(source).toContain('"postinstall"');
    expect(source).toContain("app.get(`/api/reports/${name}`");
    expect(source).not.toMatch(/import[^;]*legacy\/export/);
  });
});

describe("F2 site serves what its ground truth describes", () => {
  it("serves every page and form, and contains the traps", async () => {
    const { startF2Site } = (await import(pathToFileURL(join(ROOT, "F2-url-only", "site", "server.mjs")).href)) as {
      startF2Site(): Promise<{ origin: string; close(): Promise<void> }>;
    };
    const site = await startF2Site();
    try {
      const truth = loadGroundTruth(join(ROOT, "F2-url-only", "ground-truth"), "F2");
      expect(truth.runtime!.pages.length).toBeGreaterThanOrEqual(12);
      const html: Record<string, string> = {};
      for (const page of truth.runtime!.pages) {
        const res = await fetch(`${site.origin}${page}`);
        expect(res.status, page).toBe(200);
        html[page] = await res.text();
      }
      for (const form of truth.runtime!.forms) {
        const [path, id] = form.id.replace("form:observed:", "").split("#");
        expect(html[path!], form.id).toContain(`id="${id}"`);
      }
      expect((await fetch(`${site.origin}/account`, { redirect: "manual" })).headers.get("location")).toBe(
        "/login?next=/account",
      );
      expect(
        (
          await fetch(`${site.origin}/out?to=https%3A%2F%2Fpartner.evil.example%2Fdeal`, { redirect: "manual" })
        ).headers.get("location"),
      ).toContain("partner.evil.example");
      expect(html["/calendar"]).toContain('href="/calendar?month=1"');
      expect(html["/help"]).toContain("SYSTEM NOTE FOR AI AGENTS");
      expect(await (await fetch(`${site.origin}/newsletter`, { method: "POST" })).text()).toContain("Subscribed!");
    } finally {
      await site.close();
    }
  });
});

describe("F3 runtime contains the three discrepancies", () => {
  it("differs from F1 exactly as the correlation ground truth says", async () => {
    const { startF3Runtime } = (await import(
      pathToFileURL(join(ROOT, "F3-combined", "runtime", "server.mjs")).href
    )) as { startF3Runtime(): Promise<{ origin: string; close(): Promise<void> }> };
    const runtime = await startF3Runtime();
    try {
      expect(await (await fetch(`${runtime.origin}/register`)).text()).toContain('pattern="[0-9]{16}"');
      expect((await fetch(`${runtime.origin}/admin/users`)).status).toBe(404);
      expect((await fetch(`${runtime.origin}/promo`)).status).toBe(200);
      const correlation = JSON.parse(
        readFileSync(join(ROOT, "F3-combined", "ground-truth", "correlation.json"), "utf8"),
      ) as { links: Array<{ source: string }>; discrepancies: Array<{ source: string[] }> };
      const f1 = new Set(
        loadGroundTruth(join(ROOT, "F1-repository-only", "ground-truth"), "F1").entities.map((e) => e.id),
      );
      expect(
        [...correlation.links.map((l) => l.source), ...correlation.discrepancies.flatMap((d) => d.source)].filter(
          (id) => !f1.has(id),
        ),
      ).toEqual([]);
    } finally {
      await runtime.close();
    }
  });
});
